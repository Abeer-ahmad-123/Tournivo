import { CompetitionError, type TournamentFormat } from "./types";
const strategies: TournamentFormat[] = [
  singleElimination,
  doubleElimination,
  roundRobin(1),
  roundRobin(2),
  groupKnockout,
];
export function getFormat(id: string): TournamentFormat {
  const strategy = strategies.find((s) => s.id === id);
  if (!strategy) throw new CompetitionError("This format is not yet available for generation.");
  return strategy;
}
